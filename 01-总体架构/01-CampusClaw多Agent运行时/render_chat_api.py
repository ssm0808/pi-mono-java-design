#!/usr/bin/env python3
"""Render only the single current CampusClaw API catalog."""

from __future__ import annotations

import argparse
import html
from pathlib import Path

import render_chat_http_v1 as shared

ROOT = Path(__file__).resolve().parent
MANIFEST = ROOT / "接口契约/catalog.json"


def load_catalog() -> tuple[dict, list[dict]]:
    manifest = shared.read_json(MANIFEST)
    models, identities, keys, sources = [], set(), set(), set()
    for item in manifest["operations"]:
        source = ROOT / item["source"]
        common = shared.read_json(ROOT / item["common"])
        model = shared.expand_model(common, shared.read_json(source))
        operation = model["operation"]
        key = operation["operationKey"]
        identity = (operation["method"], operation["path"])
        shared.require(key == item["key"] and key not in keys, "Duplicate or mismatched catalog key")
        shared.require(identity not in identities, "Duplicate HTTP operation in current catalog")
        shared.require(model["api"]["basePath"] == manifest["basePath"], "Catalog base path differs")
        shared.require("历史" not in source.parts, "Historical contracts cannot enter current catalog")
        model["api"]["visibility"] = f'Internal · {item["status"]} · 目标设计，不代表已实现'
        models.append(model)
        keys.add(key)
        identities.add(identity)
        sources.add(source.resolve())
    active_sources = {path.resolve() for folder in ("接口契约/操作", "事件契约/操作", "统计契约/操作")
                      for path in (ROOT / folder).glob("*.json")}
    shared.require(sources == active_sources, "Every active operation must be registered exactly once")
    return manifest, models


def render_item(index: int, item: dict, model: dict) -> str:
    operation = model["operation"]
    key = html.escape(item["key"], quote=True)
    return (
        f'<details class="catalog-item" id="{key}" data-catalog-key="{key}">'
        '<summary><span class="catalog-line">'
        f'<span>{index + 1:02d}</span><strong>{html.escape(operation["method"])}</strong>'
        f'<span>{html.escape(operation["shortName"])}</span>'
        f'<span class="catalog-status">{html.escape(item["status"])}</span></span>'
        f'<code class="catalog-path">{html.escape(operation["path"])}</code></summary>'
        f'<p class="catalog-caveat">{html.escape(item["note"])}</p>'
        '<p class="catalog-links">'
        f'<a href="{html.escape(item["design"], quote=True)}">设计依据与实施边界</a> · '
        f'<a href="{html.escape(item["source"], quote=True)}">精确模型</a> · '
        f'<a href="#{key}">此接口链接</a></p>'
        f'<section class="company-api-review" data-operation-review="{key}" data-operation-index="{index}">'
        f'<div class="api-shell" data-api-shell>{shared.render_static(model, expand_details=True)}</div></section></details>'
    )


def build_html() -> str:
    manifest, models = load_catalog()
    cards = "\n".join(render_item(index, item, model)
                      for index, (item, model) in enumerate(zip(manifest["operations"], models)))
    css = shared.CSS_PATH.read_text(encoding="utf-8")
    css += (ROOT / "接口契约/页面资源/catalog.css").read_text(encoding="utf-8")
    script = shared.JS_PATH.read_text(encoding="utf-8")
    eager = '''  roots.forEach((root, index) => {
    if (models[index]) renderOperation(root, models[index]);
  });'''
    shared.require(script.count(eager) == 1, "Shared initialization changed; review lazy adapter")
    lazy = (ROOT / "接口契约/页面资源/catalog.js").read_text(encoding="utf-8")
    script = script.replace(eager, lazy.rstrip())
    return f'''<!doctype html>
<html lang="zh-CN"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="referrer" content="no-referrer">
<title>{html.escape(manifest["title"])}</title>
<style>{css}</style></head><body>
<!-- Generated by render_chat_api.py from the current catalog. Do not edit directly. -->
<main id="claw-current-api-catalog">
<header class="catalog-header"><h1>CampusClaw 当前接口 · {len(models)} 项</h1>
<code>{html.escape(manifest["basePath"])}</code>
<p>唯一当前接口入口。B01～B15 已全部确认；Session Events、配置映射与 Skill SSE 已统一定稿，可进入实现。统计查询为成功调用统计推荐方案，首版 scope=runtime；三表与来源同事务，尚未实施。设计状态不代表代码已合入或已部署。</p>
<p>本期不支持 FollowUp 排队；停止通过 user.interrupt，实际停止后才可提交下一条消息。</p>
<p>展开一个接口即可直接查看请求头、参数、请求示例和响应，无需逐栏展开。旧 Events 报文及三个独立控制接口不再展示。</p>
<p><a href="chat-api-index.md">维护规则与源码边界</a> · <a href="chat-follow-up-future-design.md">FollowUp 未来设计（本期不启用）</a></p>
</header>
{cards}
</main>
<script type="application/json" id="api-review-models" data-review-models>{shared.encode_models(models)}</script>
<script>{script}</script>
</body></html>
'''


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    manifest = shared.read_json(MANIFEST)
    outputs = {manifest["output"]: build_html()}
    for name, content in outputs.items():
        path = ROOT / name
        if args.check:
            shared.require(path.exists() and path.read_text(encoding="utf-8") == content,
                           f"Generated page is stale: {name}; run render_chat_api.py")
        else:
            shared.write_output(path, content)
        print(path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
